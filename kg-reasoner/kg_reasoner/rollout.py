"""Reasoning with an LLM over the KG (paper Algorithm 1), batched and token-exact.

    while not reached <answer>:
        LLM generates until </search> or </answer>
        if </search>: run the KG retrieval tool on the query entity and append
                      "<triples> ... </triples>" (these tokens are masked out of the RL/SFT loss)

Episodes are kept as token ids: generated tokens get mask 1, tool-output tokens mask 0, so
the retrieval mask is exact (no searching for tag token patterns afterwards). The same loop
drives local HF generation, offline vLLM and the OpenRLHF Ray-vLLM engines; a backend only
has to implement `generate(batch_token_ids, max_new_tokens) -> List[GenOutput]`.
"""
import logging
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass, field
from typing import Callable, Dict, List, Optional

from .prompts import ANSWER_CLOSE, SEARCH_CLOSE, STOP_STRINGS, build_prompt, format_observation, last_search_query

logger = logging.getLogger(__name__)


@dataclass
class GenOutput:
    token_ids: List[int]
    text: str
    stop: Optional[str]  # matched stop string ("</search>" / "</answer>") or None (EOS / length)


Generate = Callable[[List[List[int]], List[int]], List[GenOutput]]


@dataclass
class RolloutConfig:
    max_turns: int = 8              # max retrieval calls per episode
    max_tokens_per_turn: int = 512
    max_response_tokens: int = 4096
    append_eos: bool = True          # append EOS after </answer> so the policy learns to stop
    tool_workers: int = 16


@dataclass
class Episode:
    record: Dict
    prompt: str
    prompt_ids: List[int]
    tool: Optional[Callable[[str], str]] = None
    response_ids: List[int] = field(default_factory=list)
    response_mask: List[int] = field(default_factory=list)  # 1 = generated by the policy, 0 = tool output
    response_text: str = ""
    n_search: int = 0
    finish_reason: str = ""
    last_generated: str = ""

    @property
    def done(self) -> bool:
        return bool(self.finish_reason)

    @property
    def full_ids(self) -> List[int]:
        return self.prompt_ids + self.response_ids

    def add_generated(self, ids: List[int], text: str) -> None:
        self.response_ids += ids
        self.response_mask += [1] * len(ids)
        self.response_text += text
        self.last_generated = text

    def add_observation(self, ids: List[int], text: str) -> None:
        self.response_ids += ids
        self.response_mask += [0] * len(ids)
        self.response_text += text


def make_episode(record: Dict, tokenizer, tool_factory=None, prompt: Optional[str] = None) -> Episode:
    prompt = prompt if prompt is not None else build_prompt(record)
    ids = tokenizer(prompt, add_special_tokens=True)["input_ids"]
    return Episode(record=record, prompt=prompt, prompt_ids=ids, tool=tool_factory(record) if tool_factory else None)


def run_episodes(episodes: List[Episode], generate: Generate, tokenizer, cfg: RolloutConfig = RolloutConfig()) -> List[Episode]:
    eos = tokenizer.eos_token_id
    active = [e for e in episodes if not e.done]
    pool = ThreadPoolExecutor(max_workers=cfg.tool_workers)
    try:
        turn = 0
        while active:
            budgets = [max(1, min(cfg.max_tokens_per_turn, cfg.max_response_tokens - len(e.response_ids))) for e in active]
            outs = generate([e.full_ids for e in active], budgets)
            searching = []
            for ep, out in zip(active, outs):
                ep.add_generated(list(out.token_ids), out.text)
                over_budget = len(ep.response_ids) >= cfg.max_response_tokens
                if out.stop == SEARCH_CLOSE and turn < cfg.max_turns and not over_budget:
                    searching.append(ep)
                    continue
                if out.stop == ANSWER_CLOSE:
                    ep.finish_reason = "answer"
                    if cfg.append_eos and eos is not None:
                        ep.add_generated([eos], "")
                elif out.stop == SEARCH_CLOSE:
                    ep.finish_reason = "max_turns" if turn >= cfg.max_turns else "length"
                else:
                    ep.finish_reason = "length" if over_budget or not out.token_ids or out.token_ids[-1] != eos else "eos"
                if not ep.response_ids:
                    ep.add_generated([eos], "")
            observations = list(pool.map(_call_tool, searching))
            for ep, obs in zip(searching, observations):
                block = format_observation(obs)
                ep.add_observation(tokenizer(block, add_special_tokens=False)["input_ids"], block)
                ep.n_search += 1
            active = searching
            turn += 1
    finally:
        pool.shutdown(wait=False)
    return episodes


def _call_tool(ep: Episode) -> str:
    query = last_search_query(ep.last_generated)
    if ep.tool is None:
        return "No knowledge graph is available."
    try:
        return ep.tool(query)
    except Exception as e:  # a failing lookup must not kill a whole rollout batch
        logger.exception("KG tool failed on %r", query)
        return f"Search failed: {type(e).__name__}."


def pack_episodes(episodes: List[Episode]) -> Dict[str, List]:
    """OpenRLHF packed-sample layout: | prompt response | prompt response | ... |"""
    sequences, attention_mask, retrieve_mask = [], [], []
    num_actions, packed_seq_lens, retrieve_num, pure_len = [], [], [], []
    for i, ep in enumerate(episodes):
        seq = ep.prompt_ids + ep.response_ids
        sequences += seq
        attention_mask += [i + 1] * len(seq)
        retrieve_mask += ep.response_mask
        num_actions.append(len(ep.response_ids))
        packed_seq_lens.append(len(seq))
        retrieve_num.append(ep.n_search)
        pure_len.append(sum(ep.response_mask))
    return {"sequences": sequences, "attention_mask": attention_mask, "retrieve_mask": retrieve_mask,
            "num_actions": num_actions, "packed_seq_lens": packed_seq_lens, "retrieve_num": retrieve_num,
            "pure_response_length": pure_len}


def _match_stop(text: str) -> Optional[str]:
    tail = text.rstrip()
    for s in STOP_STRINGS:
        if tail.endswith(s):
            return s
    # a stop string can end inside the last token ("</search>\n"): look near the end
    for s in STOP_STRINGS:
        if s in text[-(len(s) + 8):]:
            return s
    return None


class HFGenerator:
    """transformers backend (single-device runs)."""

    def __init__(self, model, tokenizer, temperature: float = 1.0, top_p: float = 1.0):
        self.model, self.tokenizer, self.temperature, self.top_p = model, tokenizer, temperature, top_p

    def __call__(self, batch_ids: List[List[int]], max_new_tokens: List[int]) -> List[GenOutput]:
        import torch

        outs = []
        device = next(self.model.parameters()).device
        pad = self.tokenizer.pad_token_id if self.tokenizer.pad_token_id is not None else self.tokenizer.eos_token_id
        for ids, budget in zip(batch_ids, max_new_tokens):
            inp = torch.tensor([ids], device=device)
            sample = self.temperature > 0
            gen = self.model.generate(
                input_ids=inp, attention_mask=torch.ones_like(inp), max_new_tokens=budget, do_sample=sample,
                temperature=self.temperature if sample else None, top_p=self.top_p if sample else None,
                stop_strings=STOP_STRINGS, tokenizer=self.tokenizer, pad_token_id=pad,
            )
            new = gen[0, len(ids):].tolist()
            while new and new[-1] == pad and pad != self.tokenizer.eos_token_id:
                new.pop()
            if self.tokenizer.eos_token_id in new:  # keep up to and including EOS
                new = new[: new.index(self.tokenizer.eos_token_id) + 1]
            text = self.tokenizer.decode(new, skip_special_tokens=True)
            outs.append(GenOutput(new, text, _match_stop(text)))
        return outs


class VLLMGenerator:
    """Offline vLLM backend (evaluation, open-weight warm-up teacher)."""

    def __init__(self, llm, temperature: float = 0.0, top_p: float = 1.0):
        self.llm, self.temperature, self.top_p = llm, temperature, top_p

    def __call__(self, batch_ids: List[List[int]], max_new_tokens: List[int]) -> List[GenOutput]:
        from vllm import SamplingParams

        params = [SamplingParams(temperature=self.temperature, top_p=self.top_p, max_tokens=m, stop=STOP_STRINGS,
                                 include_stop_str_in_output=True, skip_special_tokens=False) for m in max_new_tokens]
        results = self.llm.generate([{"prompt_token_ids": ids} for ids in batch_ids], params, use_tqdm=False)
        return [vllm_to_genoutput(r) for r in results]


def vllm_to_genoutput(result) -> GenOutput:
    o = result.outputs[0]
    stop = o.stop_reason if isinstance(o.stop_reason, str) else None
    return GenOutput(list(o.token_ids), o.text, stop)
